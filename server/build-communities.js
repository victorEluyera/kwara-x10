// Regenerates server/data/communities.js from GRID3.
//
//   node server/build-communities.js
//
// The proposals candidates actually submit are organised by COMMUNITY, not by
// ward: "Ikereku -- sewing machine, solar, palliative", "Yejuade -- transformer
// cables, culvert, borehole". Free text would give us thirty spellings of
// Ikereku and nothing to group by, so the community field autocompletes from a
// real gazetteer.
//
// Source: GRID3's "Settlements in Nigeria" layer (grid3_nga_settlementpt),
// which carries a name, an alternative name, and the LGA/ward for every named
// settlement in the country. Kwara has ~11,500.
//
// Ward is stored only as a HINT, because GRID3 and INEC do not use the same
// ward set: INEC numbers the Ibadan wards ("WARD III, N4") where GRID3 names
// them ("Sabo", "Agbowo"), so roughly a third of settlements cannot be tied to
// an INEC ward by name at all. LGA, by contrast, matches for every single row.
// So the autocomplete is scoped by LGA and merely SORTS the chosen ward first
// -- offering a real community with no ward beats hiding it.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { matchLga, matchWard } from './grid3.js';
import { LGAS } from './data/geo.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, 'data', 'communities.js');

export const SETTLEMENTS_URL = process.env.GRID3_SETTLEMENTS_URL
  || 'https://services3.arcgis.com/BU6Aadhn6tbBEdyk/arcgis/rest/services/'
   + 'Settlements_in_Nigeria/FeatureServer/0/query';

const PAGE = 2000;

async function fetchKwaraSettlements() {
  const rows = [];
  for (let offset = 0; ; offset += PAGE) {
    const url = SETTLEMENTS_URL
      + '?where=' + encodeURIComponent("UPPER(statename)='KWARA'")
      + '&outFields=' + encodeURIComponent('set_name,set_altnam,wardname,lganame')
      + '&returnGeometry=true&outSR=4326'
      + '&resultOffset=' + offset + '&resultRecordCount=' + PAGE + '&f=json';
    const body = await (await fetch(url)).json();
    if (body.error) throw new Error('GRID3: ' + JSON.stringify(body.error));
    const page = body.features || [];
    for (const f of page) {
      rows.push({ ...f.attributes, lat: f.geometry?.y, lng: f.geometry?.x });
    }
    process.stderr.write(`  ${rows.length} settlements\n`);
    if (page.length < PAGE) return rows;
  }
}

const tidy = (s) => String(s || '').trim().replace(/\s+/g, ' ');
const round = (n) => Math.round(n * 1e4) / 1e4;   // ~11 m, plenty to centre a map

/** Group settlements by our LGA names, de-duplicated on name + ward hint. */
export function organise(rows) {
  const byLga = new Map(LGAS.map((l) => [l, new Map()]));
  const skipped = [];

  for (const row of rows) {
    const lga = matchLga(row.lganame);
    const name = tidy(row.set_name);
    if (!lga || !name || !Number.isFinite(row.lat)) { skipped.push(row); continue; }

    const ward = matchWard(lga, row.wardname) || '';
    const alt = tidy(row.set_altnam);
    const key = name.toUpperCase() + '|' + ward.toUpperCase();
    const seen = byLga.get(lga);
    // Keep the first of a repeated name; only fill in an alt name we lacked.
    if (seen.has(key)) {
      if (alt && !seen.get(key)[2]) seen.get(key)[2] = alt;
      continue;
    }
    seen.set(key, [name, ward, alt && alt !== name ? alt : '', round(row.lat), round(row.lng)]);
  }

  const out = {};
  for (const lga of LGAS) {
    out[lga] = [...byLga.get(lga).values()]
      .sort((a, b) => a[0].localeCompare(b[0], 'en'));
  }
  return { out, skipped };
}

function render(byLga) {
  const total = Object.values(byLga).reduce((n, v) => n + v.length, 0);
  const withWard = Object.values(byLga).flat().filter((c) => c[1]).length;

  const body = Object.entries(byLga).map(([lga, list]) =>
    '  ' + JSON.stringify(lga) + ': [\n'
    + list.map((c) => '    ' + JSON.stringify(c)).join(',\n')
    + '\n  ],').join('\n');

  return `// GENERATED by server/build-communities.js -- do not edit by hand.
//
// Named communities in Kwara State, from GRID3's settlement gazetteer, so that
// the community field on a project autocompletes instead of accepting thirty
// spellings of the same village.
//
//   ${total} communities across ${LGAS.length} LGAs
//   ${withWard} (${Math.round((100 * withWard) / total)}%) also carry an INEC ward
//
// Each entry is [name, ward, alternative name, lat, lng]. Ward is '' where
// GRID3's ward set does not line up with INEC's -- see build-communities.js.
// Those communities are still offered, they just cannot be filtered by ward.

/** @type {Record<string, Array<[string, string, string, number, number]>>} */
export const RAW = {
${body}
};

export const COMMUNITY_COUNT = ${total};

const shape = ([name, ward, alt, lat, lng]) => ({ name, ward, alt, lat, lng });

/**
 * Communities to offer for an LGA. With a ward, the ones known to sit in that
 * ward come first; the rest of the LGA follows, because a third of GRID3's
 * settlements cannot be tied to an INEC ward and hiding them would make real
 * places untypeable.
 */
export function communitiesIn(lga, ward) {
  const all = (RAW[lga] || []).map(shape);
  if (!ward) return all;
  const here = [], elsewhere = [];
  for (const c of all) (c.ward === ward ? here : elsewhere).push(c);
  return [...here, ...elsewhere];
}

/** Look one up by name (or alternative name) within an LGA. */
export function findCommunity(lga, name) {
  const want = String(name || '').trim().toUpperCase();
  if (!want) return null;
  return (RAW[lga] || []).map(shape).find(
    (c) => c.name.toUpperCase() === want || (c.alt && c.alt.toUpperCase() === want)) || null;
}

/** Type-ahead: prefix matches first, then anything containing the term. */
export function searchCommunities(lga, ward, term, limit = 20) {
  const want = String(term || '').trim().toUpperCase();
  const pool = communitiesIn(lga, ward);
  if (!want) return pool.slice(0, limit);
  const starts = [], holds = [];
  for (const c of pool) {
    const hay = (c.name + ' ' + c.alt).toUpperCase();
    if (c.name.toUpperCase().startsWith(want)) starts.push(c);
    else if (hay.includes(want)) holds.push(c);
    if (starts.length >= limit) break;
  }
  return [...starts, ...holds].slice(0, limit);
}
`;
}

const invokedDirectly = String(process.argv[1] || '').endsWith('build-communities.js');
if (invokedDirectly) {
  process.stderr.write('Pulling Kwara settlements from GRID3...\n');
  const rows = await fetchKwaraSettlements();
  const { out, skipped } = organise(rows);
  fs.writeFileSync(OUT, render(out));
  const total = Object.values(out).reduce((n, v) => n + v.length, 0);
  process.stderr.write(`\nWrote ${OUT}\n  ${total} communities kept`
    + ` (${rows.length} rows in, ${rows.length - total} duplicates/unusable)\n`);
  if (skipped.length) process.stderr.write(`  ${skipped.length} rows had no usable LGA or point\n`);
}
